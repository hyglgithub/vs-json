// 三个空态各一句话。
//
// **这里曾经是从 HELP_SECTIONS 里挑几节渲染的**（HINT_PICK + 标题 + 条目 + 末尾指路），
// 好处是绝不会和帮助面板说岔。但用户看到后要求推倒：空白面板上摊开一整节说明还是太吵，
// 「文字描述还是太多了，最好一段话说完，没有分层」。
// 于是空态和帮助面板变成了**两种体裁**——空态是「指个路」，帮助面板才是手册。
// 代价是这里不再由 HELP_SECTIONS 派生，两边理论上会漂移；压住它的办法是
// 两条：放在同一个文件里（改文案时一定看得见），以及只写那种不会随功能细节变的话。
// 所以这里**不要**写按钮的具体行为、不要写数字上限以外的东西——细节都在上面那十节里，
// 重复一遍就是给自己埋一个将来对不上的地方。
//
// 保存记录那一条是例外：两个上限必须露出来，否则条目被裁掉时用户不知道有闸。
